export const PAYMENT_METHODS = [
  { id: "cash", labelKey: "method.cash" },
  { id: "debit", labelKey: "method.debit" },
  { id: "credit", labelKey: "method.credit" },
  { id: "transfer", labelKey: "method.transfer" },
  { id: "yape", labelKey: "method.yape" },
  { id: "plin", labelKey: "method.plin" },
] as const;

// Los movimientos guardados antes de este cambio tienen el método de
// pago escrito tal cual (ej. "Tarjeta débito"), no un identificador. Si
// no lo reconocemos como uno de los métodos actuales, mostramos el
// texto tal como se guardó en vez de romper algo.
export function methodLabel(method: string, t: (key: string) => string): string {
  const known = PAYMENT_METHODS.find((m) => m.id === method);
  return known ? t(known.labelKey) : method;
}

