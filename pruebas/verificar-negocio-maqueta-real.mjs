function cargar(entry) {
  const result = buildSync({entryPoints:[entry],bundle:true,write:false,format:'cjs',platform:'node',alias:{'@':process.cwd(),'@/utils/storage':path.resolve('pruebas/stubs/negocio-workspace-storage.ts')},logLevel:'silent'});
  const module={exports:{}};
  vm.runInNewContext(result.outputFiles[0].text,{module,exports:module.exports,console,Date,Math,Set,Map});
  return module.exports;
}
